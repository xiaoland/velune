//! Emits the generated half of the Go package: FFI declarations, types and converters.
//!
//! Names follow one scheme so the static runtime can refer to them: every type has a
//! key, `read<key>`/`write<key>` move it through a RustBuffer, and objects add
//! `lift<name>`/`lower<name>` for their handles.
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;
use uniffi_bindgen::interface::{
    AsType, ComponentInterface, Enum, FfiFunction, FfiType, Object, Record, Type,
};

pub type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;

/// One exported callable, already reduced to what the Go wrapper needs.
struct Call<'a> {
    doc: Option<&'a str>,
    receiver: Option<&'a str>,
    name: String,
    args: Vec<(String, Type)>,
    returns: Option<Type>,
    throws: Option<Type>,
    ffi: &'a FfiFunction,
}

pub fn bindings(ci: &ComponentInterface) -> Result<String> {
    unsupported(ci)?;
    let mut emitter = Emitter {
        ci,
        out: String::new(),
        exported: BTreeSet::from(["Load".to_owned()]),
        uses_time: false,
    };
    emitter.ffi_declarations()?;
    for record in ci.record_definitions() {
        emitter.record(record)?;
    }
    for enum_ in ci.enum_definitions() {
        emitter.enum_(enum_)?;
    }
    for object in ci.object_definitions() {
        emitter.object(object)?;
    }
    for function in ci.function_definitions() {
        emitter.call(&Call {
            doc: function.docstring(),
            receiver: None,
            name: upper_camel(function.name()),
            args: arguments(
                function
                    .arguments()
                    .into_iter()
                    .map(|a| (a.name(), a.as_type())),
            ),
            returns: function.return_type().cloned(),
            throws: function.throws_type().cloned(),
            ffi: function.ffi_func(),
        })?;
    }
    emitter.compounds()?;
    let mut header =
        String::from("// Code generated by velune-gobindgen. DO NOT EDIT.\n\npackage bindings\n");
    if emitter.uses_time {
        header.push_str("\nimport \"time\"\n");
    }
    Ok(header + &emitter.out)
}

/// Rejects interface features this generator does not translate, instead of
/// silently dropping them from the Go package.
fn unsupported(ci: &ComponentInterface) -> Result<()> {
    if ci.has_async_fns() || ci.has_callback_definitions() {
        return Err("async 函数与 callback interface 尚未支持".into());
    }
    for object in ci.object_definitions() {
        if object.is_trait_interface() || !object.uniffi_traits().is_empty() {
            return Err(format!("{} 使用了 trait interface 或 uniffi trait", object.name()).into());
        }
    }
    for record in ci.record_definitions() {
        if !record.methods().is_empty() || !record.constructors().is_empty() {
            return Err(format!("record {} 带有方法", record.name()).into());
        }
    }
    for enum_ in ci.enum_definitions() {
        if !enum_.methods().is_empty() || !enum_.constructors().is_empty() {
            return Err(format!("enum {} 带有方法", enum_.name()).into());
        }
        if enum_.is_flat() && ci.is_name_used_as_error(enum_.name()) {
            return Err(format!("flat error {} 尚未支持", enum_.name()).into());
        }
    }
    Ok(())
}

struct Emitter<'a> {
    ci: &'a ComponentInterface,
    out: String,
    exported: BTreeSet<String>,
    uses_time: bool,
}

impl Emitter<'_> {
    fn export(&mut self, name: &str) -> Result<()> {
        if self.exported.insert(name.to_owned()) {
            Ok(())
        } else {
            Err(format!("Go 标识符 {name} 重复").into())
        }
    }

    fn doc(&mut self, indent: &str, doc: Option<&str>) -> Result<()> {
        for line in doc.into_iter().flat_map(str::lines) {
            writeln!(self.out, "{indent}// {}", line.trim_end())?;
        }
        Ok(())
    }

    fn ffi_declarations(&mut self) -> Result<()> {
        let functions = self
            .ci
            .iter_ffi_function_definitions_non_async()
            .collect::<Vec<_>>();
        writeln!(self.out, "\nvar (")?;
        for function in &functions {
            let mut params = function
                .arguments()
                .into_iter()
                .map(|argument| ffi_go_type(&argument.type_()))
                .collect::<Result<Vec<_>>>()?;
            if function.has_rust_call_status_arg() {
                params.push("*rustCallStatus".into());
            }
            let result = match function.return_type() {
                Some(ty) => format!(" {}", ffi_go_type(ty)?),
                None => String::new(),
            };
            writeln!(
                self.out,
                "\t{} func({}){result}",
                function.name(),
                params.join(", ")
            )?;
        }
        writeln!(self.out, ")\n\nvar ffiSymbols = []ffiSymbol{{")?;
        for function in &functions {
            writeln!(self.out, "\t{{{0:?}, &{0}}},", function.name())?;
        }
        writeln!(self.out, "}}\n\nvar ffiChecksums = []ffiChecksum{{")?;
        for (name, checksum) in self.ci.iter_checksums() {
            writeln!(self.out, "\t{{{name:?}, &{name}, {checksum}}},")?;
        }
        writeln!(
            self.out,
            "}}\n\nconst contractVersion = {}\n\nfunc ffiContractVersion() uint32 {{ return {}() }}",
            self.ci.uniffi_contract_version(),
            self.ci.ffi_uniffi_contract_version().name()
        )?;
        writeln!(
            self.out,
            "\nfunc rustBufferAlloc(size uint64, status *rustCallStatus) rustBuffer {{\n\treturn {}(size, status)\n}}",
            self.ci.ffi_rustbuffer_alloc().name()
        )?;
        writeln!(
            self.out,
            "\nfunc rustBufferFree(buffer rustBuffer, status *rustCallStatus) {{\n\t{}(buffer, status)\n}}",
            self.ci.ffi_rustbuffer_free().name()
        )?;
        Ok(())
    }

    fn record(&mut self, record: &Record) -> Result<()> {
        let name = record.name();
        self.export(name)?;
        writeln!(self.out)?;
        self.doc("", record.docstring())?;
        writeln!(self.out, "type {name} struct {{")?;
        let mut fields = Vec::new();
        for field in record.fields() {
            let go_name = upper_camel(field.name());
            self.doc("\t", field.docstring())?;
            writeln!(self.out, "\t{go_name} {}", self.go_type(&field.as_type())?)?;
            fields.push((go_name, field.as_type()));
        }
        writeln!(
            self.out,
            "}}\n\nfunc read{name}(r *reader) {name} {{\n\tvar v {name}"
        )?;
        for (go_name, ty) in &fields {
            writeln!(self.out, "\tv.{go_name} = read{}(r)", key(ty)?)?;
        }
        writeln!(
            self.out,
            "\treturn v\n}}\n\nfunc write{name}(w *writer, v {name}) {{"
        )?;
        for (go_name, ty) in &fields {
            writeln!(self.out, "\twrite{}(w, v.{go_name})", key(ty)?)?;
        }
        writeln!(self.out, "}}")?;
        Ok(())
    }

    fn enum_(&mut self, enum_: &Enum) -> Result<()> {
        let name = enum_.name();
        self.export(name)?;
        writeln!(self.out)?;
        self.doc("", enum_.docstring())?;
        if enum_.is_flat() {
            return self.flat_enum(enum_);
        }
        let is_error = self.ci.is_name_used_as_error(name);
        if is_error {
            writeln!(
                self.out,
                "type {name} interface {{\n\terror\n\tis{name}()\n}}"
            )?;
        } else {
            writeln!(self.out, "type {name} interface{{ is{name}() }}")?;
        }
        let mut variants = Vec::new();
        for variant in enum_.variants() {
            let go_name = format!("{name}{}", upper_camel(variant.name()));
            self.export(&go_name)?;
            writeln!(self.out)?;
            self.doc("", variant.docstring())?;
            writeln!(self.out, "type {go_name} struct {{")?;
            let mut fields = Vec::new();
            for (index, field) in variant.fields().iter().enumerate() {
                let field_name = if field.name().is_empty() {
                    format!("Field{index}")
                } else {
                    upper_camel(field.name())
                };
                if is_error && field_name == "Error" {
                    return Err(format!("{go_name} 的字段与 Error 方法冲突").into());
                }
                self.doc("\t", field.docstring())?;
                writeln!(
                    self.out,
                    "\t{field_name} {}",
                    self.go_type(&field.as_type())?
                )?;
                fields.push((field_name, field.as_type()));
            }
            writeln!(self.out, "}}\n\nfunc ({go_name}) is{name}() {{}}")?;
            if is_error {
                // Rust formats these messages itself; the detail field carries the
                // user-facing text whenever a variant has one.
                let message = if fields.iter().any(|(field, _)| field == "Detail") {
                    "e.Detail".to_owned()
                } else {
                    format!("{:?}", variant.name())
                };
                writeln!(
                    self.out,
                    "\nfunc (e {go_name}) Error() string {{ return {message} }}"
                )?;
            }
            variants.push((go_name, fields));
        }
        let binds = variants.iter().any(|(_, fields)| !fields.is_empty());
        writeln!(
            self.out,
            "\nfunc read{name}(r *reader) {name} {{\n\tswitch index := int32(r.u32()); index {{"
        )?;
        for (index, (go_name, fields)) in variants.iter().enumerate() {
            writeln!(self.out, "\tcase {}:", index + 1)?;
            if fields.is_empty() {
                writeln!(self.out, "\t\treturn {go_name}{{}}")?;
                continue;
            }
            writeln!(self.out, "\t\tvar v {go_name}")?;
            for (field, ty) in fields {
                writeln!(self.out, "\t\tv.{field} = read{}(r)", key(ty)?)?;
            }
            writeln!(self.out, "\t\treturn v")?;
        }
        writeln!(
            self.out,
            "\tdefault:\n\t\tpanic(unexpectedVariant({name:?}, index))\n\t}}\n}}"
        )?;
        let switch = if binds { "v := v.(type)" } else { "v.(type)" };
        writeln!(
            self.out,
            "\nfunc write{name}(w *writer, v {name}) {{\n\tswitch {switch} {{"
        )?;
        for (index, (go_name, fields)) in variants.iter().enumerate() {
            writeln!(self.out, "\tcase {go_name}:\n\t\tw.u32({})", index + 1)?;
            for (field, ty) in fields {
                writeln!(self.out, "\t\twrite{}(w, v.{field})", key(ty)?)?;
            }
        }
        writeln!(
            self.out,
            "\tdefault:\n\t\tpanic(\"velune: unknown {name} variant\")\n\t}}\n}}"
        )?;
        if is_error {
            writeln!(
                self.out,
                "\nfunc liftError{name}(buffer rustBuffer) error {{ return liftFromRustBuffer(buffer, read{name}) }}"
            )?;
        }
        Ok(())
    }

    fn flat_enum(&mut self, enum_: &Enum) -> Result<()> {
        let name = enum_.name();
        writeln!(self.out, "type {name} int32\n\nconst (")?;
        for (index, variant) in enum_.variants().iter().enumerate() {
            let go_name = format!("{name}{}", upper_camel(variant.name()));
            self.export(&go_name)?;
            self.doc("\t", variant.docstring())?;
            writeln!(self.out, "\t{go_name} {name} = {}", index + 1)?;
        }
        writeln!(
            self.out,
            ")\n\nfunc read{name}(r *reader) {name} {{\n\tindex := int32(r.u32())\n\tif index < 1 || index > {} {{\n\t\tpanic(unexpectedVariant({name:?}, index))\n\t}}\n\treturn {name}(index)\n}}",
            enum_.variants().len()
        )?;
        writeln!(
            self.out,
            "\nfunc write{name}(w *writer, v {name}) {{ w.u32(uint32(v)) }}"
        )?;
        Ok(())
    }

    fn object(&mut self, object: &Object) -> Result<()> {
        let name = object.name();
        self.export(name)?;
        writeln!(self.out)?;
        self.doc("", object.docstring())?;
        writeln!(
            self.out,
            "type {name} struct{{ h *objectHandle }}\n\nfunc lift{name}(raw uint64) *{name} {{\n\treturn &{name}{{newObjectHandle(raw, {}, {})}}\n}}",
            object.ffi_object_clone().name(),
            object.ffi_object_free().name()
        )?;
        writeln!(
            self.out,
            "\nfunc lower{name}(v *{name}) uint64 {{ return v.h.handle() }}\n\nfunc read{name}(r *reader) *{name} {{ return lift{name}(r.u64()) }}\n\nfunc write{name}(w *writer, v *{name}) {{ w.u64(lower{name}(v)) }}"
        )?;
        writeln!(
            self.out,
            "\n// Destroy releases the Rust object now rather than when the garbage collector finds it.\nfunc (o *{name}) Destroy() {{ o.h.release() }}"
        )?;
        for constructor in object.constructors() {
            let go_name = if constructor.is_primary_constructor() {
                format!("New{name}")
            } else {
                format!("{name}{}", upper_camel(constructor.name()))
            };
            self.call(&Call {
                doc: constructor.docstring(),
                receiver: None,
                name: go_name,
                args: arguments(
                    constructor
                        .arguments()
                        .into_iter()
                        .map(|a| (a.name(), a.as_type())),
                ),
                returns: Some(object.as_type()),
                throws: constructor.throws_type().cloned(),
                ffi: constructor.ffi_func(),
            })?;
        }
        let mut methods = BTreeSet::from(["Destroy".to_owned()]);
        for method in object.methods() {
            let go_name = upper_camel(method.name());
            if !methods.insert(go_name.clone()) {
                return Err(format!("{name}.{go_name} 重复").into());
            }
            self.call(&Call {
                doc: method.docstring(),
                receiver: Some(name),
                name: go_name,
                args: arguments(
                    method
                        .arguments()
                        .into_iter()
                        .map(|a| (a.name(), a.as_type())),
                ),
                returns: method.return_type().cloned(),
                throws: method.throws_type().cloned(),
                ffi: method.ffi_func(),
            })?;
        }
        Ok(())
    }

    fn call(&mut self, call: &Call) -> Result<()> {
        if call.receiver.is_none() {
            self.export(&call.name)?;
        }
        let mut params = Vec::new();
        let mut ffi_args = Vec::new();
        if call.receiver.is_some() {
            ffi_args.push("o.h.handle()".to_owned());
        }
        for (name, ty) in &call.args {
            params.push(format!("{name} {}", self.go_type(ty)?));
            ffi_args.push(lower(ty, name)?);
        }
        ffi_args.push("ffiStatus".into());
        let returns = call
            .returns
            .as_ref()
            .map(|ty| self.go_type(ty))
            .transpose()?;
        let results = match (&returns, call.throws.is_some()) {
            (Some(ty), true) => format!(" ({ty}, error)"),
            (Some(ty), false) => format!(" {ty}"),
            (None, true) => " error".into(),
            (None, false) => String::new(),
        };
        let receiver = call
            .receiver
            .map(|name| format!("(o *{name}) "))
            .unwrap_or_default();
        writeln!(self.out)?;
        self.doc("", call.doc)?;
        writeln!(
            self.out,
            "func {receiver}{}({}){results} {{",
            call.name,
            params.join(", ")
        )?;
        let invoke = format!("{}({})", call.ffi.name(), ffi_args.join(", "));
        let closure = match call.ffi.return_type() {
            Some(ty) => format!(
                "func(ffiStatus *rustCallStatus) {} {{\n\t\treturn {invoke}\n\t}}",
                ffi_go_type(ty)?
            ),
            None => format!(
                "func(ffiStatus *rustCallStatus) struct{{}} {{\n\t\t{invoke}\n\t\treturn struct{{}}{{}}\n\t}}"
            ),
        };
        match (&call.returns, &call.throws) {
            (Some(ty), Some(error)) => writeln!(
                self.out,
                "\tffiResult, err := rustCall({closure}, liftError{})\n\tif err != nil {{\n\t\tvar zero {}\n\t\treturn zero, err\n\t}}\n\treturn {}, nil",
                key(error)?,
                returns.as_deref().unwrap_or_default(),
                lift(ty, "ffiResult")?
            )?,
            (Some(ty), None) => writeln!(
                self.out,
                "\treturn {}",
                lift(ty, &format!("rustCallNoError({closure})"))?
            )?,
            (None, Some(error)) => writeln!(
                self.out,
                "\t_, err := rustCall({closure}, liftError{})\n\treturn err",
                key(error)?
            )?,
            (None, None) => writeln!(self.out, "\trustCallNoError({closure})")?,
        }
        writeln!(self.out, "}}")?;
        Ok(())
    }

    /// Converters for the optional, sequence and map types the interface uses.
    fn compounds(&mut self) -> Result<()> {
        let mut types = BTreeMap::new();
        for ty in self.ci.iter_local_types() {
            let ty = canonical(ty);
            if let Some(existing) = types.insert(key(ty)?, ty)
                && existing != ty
            {
                return Err(format!("{existing:?} 与 {ty:?} 的转换函数同名").into());
            }
        }
        for (key, ty) in types {
            let go_type = self.go_type(ty)?;
            match ty {
                Type::Timestamp | Type::Duration => self.uses_time = true,
                Type::Optional { inner_type } => {
                    let inner = self::key(inner_type)?;
                    let (wrap, unwrap) = if self.nilable(inner_type) {
                        ("v", "v")
                    } else {
                        ("&v", "*v")
                    };
                    writeln!(
                        self.out,
                        "\nfunc read{key}(r *reader) {go_type} {{\n\tif r.u8() == 0 {{\n\t\treturn nil\n\t}}\n\tv := read{inner}(r)\n\treturn {wrap}\n}}"
                    )?;
                    writeln!(
                        self.out,
                        "\nfunc write{key}(w *writer, v {go_type}) {{\n\tif v == nil {{\n\t\tw.u8(0)\n\t\treturn\n\t}}\n\tw.u8(1)\n\twrite{inner}(w, {unwrap})\n}}"
                    )?;
                }
                Type::Sequence { inner_type } => {
                    let inner = self::key(inner_type)?;
                    writeln!(
                        self.out,
                        "\nfunc read{key}(r *reader) {go_type} {{\n\tn := r.length()\n\tv := make({go_type}, 0, n)\n\tfor range n {{\n\t\tv = append(v, read{inner}(r))\n\t}}\n\treturn v\n}}"
                    )?;
                    writeln!(
                        self.out,
                        "\nfunc write{key}(w *writer, v {go_type}) {{\n\tw.length(len(v))\n\tfor _, e := range v {{\n\t\twrite{inner}(w, e)\n\t}}\n}}"
                    )?;
                }
                Type::Set { inner_type } => {
                    let inner = self::key(inner_type)?;
                    writeln!(
                        self.out,
                        "\nfunc read{key}(r *reader) {go_type} {{\n\tn := r.length()\n\tv := make({go_type}, n)\n\tfor range n {{\n\t\tv[read{inner}(r)] = struct{{}}{{}}\n\t}}\n\treturn v\n}}"
                    )?;
                    writeln!(
                        self.out,
                        "\nfunc write{key}(w *writer, v {go_type}) {{\n\tw.length(len(v))\n\tfor e := range v {{\n\t\twrite{inner}(w, e)\n\t}}\n}}"
                    )?;
                }
                Type::Map {
                    key_type,
                    value_type,
                } => {
                    let (k, v) = (self::key(key_type)?, self::key(value_type)?);
                    writeln!(
                        self.out,
                        "\nfunc read{key}(r *reader) {go_type} {{\n\tn := r.length()\n\tv := make({go_type}, n)\n\tfor range n {{\n\t\tk := read{k}(r)\n\t\tv[k] = read{v}(r)\n\t}}\n\treturn v\n}}"
                    )?;
                    writeln!(
                        self.out,
                        "\nfunc write{key}(w *writer, v {go_type}) {{\n\tw.length(len(v))\n\tfor k, e := range v {{\n\t\twrite{k}(w, k)\n\t\twrite{v}(w, e)\n\t}}\n}}"
                    )?;
                }
                _ => {}
            }
        }
        Ok(())
    }

    /// Objects and enums with data are already nil-able in Go, so an optional
    /// one needs no extra pointer.
    fn nilable(&self, ty: &Type) -> bool {
        match canonical(ty) {
            Type::Object { .. } => true,
            Type::Enum { name, .. } => self
                .ci
                .get_enum_definition(name)
                .is_some_and(|enum_| !enum_.is_flat()),
            _ => false,
        }
    }

    fn go_type(&self, ty: &Type) -> Result<String> {
        Ok(match canonical(ty) {
            Type::Object { name, .. } => format!("*{name}"),
            Type::Record { name, .. } | Type::Enum { name, .. } => name.clone(),
            Type::Optional { inner_type } if self.nilable(inner_type) => {
                self.go_type(inner_type)?
            }
            Type::Optional { inner_type } => format!("*{}", self.go_type(inner_type)?),
            Type::Sequence { inner_type } => format!("[]{}", self.go_type(inner_type)?),
            Type::Set { inner_type } => format!("map[{}]struct{{}}", self.go_type(inner_type)?),
            Type::Map {
                key_type,
                value_type,
            } => format!(
                "map[{}]{}",
                self.go_type(key_type)?,
                self.go_type(value_type)?
            ),
            primitive => primitive_go_type(primitive)?.to_owned(),
        })
    }
}

fn arguments<'a>(args: impl Iterator<Item = (&'a str, Type)>) -> Vec<(String, Type)> {
    args.map(|(name, ty)| (parameter_name(name), ty)).collect()
}

/// Box and custom types travel exactly like the type they wrap.
fn canonical(ty: &Type) -> &Type {
    match ty {
        Type::Box { inner_type } => canonical(inner_type),
        Type::Custom { builtin, .. } => canonical(builtin),
        other => other,
    }
}

fn key(ty: &Type) -> Result<String> {
    Ok(match canonical(ty) {
        Type::Object { name, .. } | Type::Record { name, .. } | Type::Enum { name, .. } => {
            name.clone()
        }
        Type::Optional { inner_type } => format!("Optional{}", key(inner_type)?),
        Type::Sequence { inner_type } => format!("Sequence{}", key(inner_type)?),
        Type::Set { inner_type } => format!("Set{}", key(inner_type)?),
        Type::Map {
            key_type,
            value_type,
        } => format!("Map{}{}", key(key_type)?, key(value_type)?),
        Type::Bytes => "Bytes".into(),
        Type::Timestamp => "Timestamp".into(),
        Type::Duration => "Duration".into(),
        primitive => upper_camel(primitive_go_type(primitive)?),
    })
}

fn primitive_go_type(ty: &Type) -> Result<&'static str> {
    Ok(match ty {
        Type::UInt8 => "uint8",
        Type::Int8 => "int8",
        Type::UInt16 => "uint16",
        Type::Int16 => "int16",
        Type::UInt32 => "uint32",
        Type::Int32 => "int32",
        Type::UInt64 => "uint64",
        Type::Int64 => "int64",
        Type::Float32 => "float32",
        Type::Float64 => "float64",
        Type::Boolean => "bool",
        Type::String => "string",
        Type::Bytes => "[]byte",
        Type::Timestamp => "time.Time",
        Type::Duration => "time.Duration",
        other => return Err(format!("{other:?} 尚未支持").into()),
    })
}

/// The Go expression that hands `value` to Rust in its FFI representation.
fn lower(ty: &Type, value: &str) -> Result<String> {
    Ok(match canonical(ty) {
        Type::Boolean => format!("lowerBool({value})"),
        Type::String => format!("lowerString({value})"),
        Type::Object { name, .. } => format!("lower{name}({value})"),
        ty if is_scalar(ty) => value.to_owned(),
        ty => format!("lowerIntoRustBuffer({value}, write{})", key(ty)?),
    })
}

/// The Go expression that takes ownership of `value` returned by Rust.
fn lift(ty: &Type, value: &str) -> Result<String> {
    Ok(match canonical(ty) {
        Type::Boolean => format!("{value} != 0"),
        Type::String => format!("liftString({value})"),
        Type::Object { name, .. } => format!("lift{name}({value})"),
        ty if is_scalar(ty) => value.to_owned(),
        ty => format!("liftFromRustBuffer({value}, read{})", key(ty)?),
    })
}

fn is_scalar(ty: &Type) -> bool {
    matches!(
        ty,
        Type::UInt8
            | Type::Int8
            | Type::UInt16
            | Type::Int16
            | Type::UInt32
            | Type::Int32
            | Type::UInt64
            | Type::Int64
            | Type::Float32
            | Type::Float64
    )
}

fn ffi_go_type(ty: &FfiType) -> Result<String> {
    Ok(match ty {
        FfiType::UInt8 => "uint8".into(),
        FfiType::Int8 => "int8".into(),
        FfiType::UInt16 => "uint16".into(),
        FfiType::Int16 => "int16".into(),
        FfiType::UInt32 => "uint32".into(),
        FfiType::Int32 => "int32".into(),
        FfiType::UInt64 | FfiType::Handle => "uint64".into(),
        FfiType::Int64 => "int64".into(),
        FfiType::Float32 => "float32".into(),
        FfiType::Float64 => "float64".into(),
        FfiType::RustBuffer(_) => "rustBuffer".into(),
        FfiType::ForeignBytes => "foreignBytes".into(),
        FfiType::RustCallStatus => "rustCallStatus".into(),
        FfiType::Reference(inner) | FfiType::MutReference(inner) => {
            format!("*{}", ffi_go_type(inner)?)
        }
        other => return Err(format!("FFI 类型 {other:?} 尚未支持").into()),
    })
}

fn upper_camel(name: &str) -> String {
    name.split('_')
        .map(|part| {
            let mut chars = part.chars();
            chars
                .next()
                .map(|first| first.to_uppercase().chain(chars).collect::<String>())
                .unwrap_or_default()
        })
        .collect()
}

/// Rust parameter names become lowerCamel Go names that cannot shadow Go
/// keywords, builtins, the `time` package or the wrapper's own locals.
fn parameter_name(name: &str) -> String {
    const RESERVED: &[&str] = &[
        "break",
        "case",
        "chan",
        "const",
        "continue",
        "default",
        "defer",
        "else",
        "fallthrough",
        "for",
        "func",
        "go",
        "goto",
        "if",
        "import",
        "interface",
        "map",
        "package",
        "range",
        "return",
        "select",
        "struct",
        "switch",
        "type",
        "var",
        "any",
        "append",
        "bool",
        "byte",
        "cap",
        "clear",
        "close",
        "copy",
        "delete",
        "error",
        "false",
        "int",
        "len",
        "make",
        "max",
        "min",
        "new",
        "nil",
        "panic",
        "print",
        "println",
        "recover",
        "string",
        "true",
        "time",
        "o",
        "err",
        "zero",
        "ffiResult",
        "ffiStatus",
    ];
    let camel = upper_camel(name);
    let mut chars = camel.chars();
    let lower = chars
        .next()
        .map(|first| first.to_lowercase().chain(chars).collect::<String>())
        .unwrap_or_default();
    if RESERVED.contains(&lower.as_str()) {
        lower + "Arg"
    } else {
        lower
    }
}
